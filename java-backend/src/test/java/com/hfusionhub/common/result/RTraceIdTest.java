package com.hfusionhub.common.result;

import com.hfusionhub.config.TraceContext;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;
import org.slf4j.MDC;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Unit tests for {@link R} — verifying that {@code traceId} is auto-populated
 * from MDC and appears in the JSON response.
 */
class RTraceIdTest {

    @AfterEach
    void cleanup() {
        TraceContext.clear();
    }

    @Test
    void okShouldIncludeTraceIdFromMDC() {
        TraceContext.set("test-trace-abc");
        R<String> response = R.ok("hello");

        assertEquals("test-trace-abc", response.getTraceId());
    }

    @Test
    void failShouldIncludeTraceIdFromMDC() {
        TraceContext.set("fail-trace-xyz");
        R<Void> response = R.fail("something broke");

        assertEquals("fail-trace-xyz", response.getTraceId());
    }

    @Test
    void traceIdShouldBeNullWhenMDCIsEmpty() {
        TraceContext.clear();
        R<String> response = R.ok("no-trace");

        assertNull(response.getTraceId());
    }

    @Test
    void traceIdShouldBeUUID32CharsWhenAutoGenerated() {
        TraceContext.create(); // generates UUID and puts in MDC
        R<String> response = R.ok("auto");

        String traceId = response.getTraceId();
        assertNotNull(traceId);
        assertEquals(32, traceId.length(), "UUID without dashes should be 32 chars");
        assertFalse(traceId.contains("-"));
    }

    @Test
    void traceIdShouldSurviveMultipleRConstructors() {
        TraceContext.set("persistent-trace");
        R<String> r1 = R.ok("first");
        R<String> r2 = R.ok("second");

        assertEquals("persistent-trace", r1.getTraceId());
        assertEquals("persistent-trace", r2.getTraceId());
    }
}
